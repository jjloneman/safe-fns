/*
 * The toBasicAscii fold audit's host half: validates the report the
 * `fold-audit` container prints, and renders it as the Markdown table under
 * `research/audits/`.
 */

/** The groups the audit lists, each with its heading, in table order. */
export const FOLD_GROUPS = {
  letter: "Latin letters",
  punctuation: "Punctuation",
  space: "Spaces",
  // eslint-disable-next-line perfectionist/sort-objects -- table order, not alphabetical.
  currency: "Currency",
  symbol: "Symbols",
} as const;

/** The whole report the container prints. */
export type FoldAuditReport = {
  /**
   * The any-ascii version the reference spellings come from.
   *
   * @example "0.3.3"
   */
  anyAsciiVersion: string;

  /**
   * The Node version the scan ran on.
   *
   * @example "26.1.0"
   */
  node: string;

  /**
   * The listed code points, in code-point order.
   *
   * @example `[{ anyAscii: "Ng", category: "Lu", codePoint: 330, folded: "", group: "letter" }]`
   */
  rows: readonly FoldAuditRow[];

  /**
   * How many assigned code points don't fold, listed or not.
   *
   * @example 167887
   */
  unfoldable: number;

  /**
   * The Unicode version of the Node that ran the scan.
   *
   * @example "16.0"
   */
  unicode: string;
};

/** One code point the planned rules can't fold to ASCII. */
export type FoldAuditRow = {
  /**
   * any-ascii's spelling, as a reference only.
   *
   * @example "Ng"
   */
  anyAscii: string;

  /**
   * Its Unicode general category.
   *
   * @example "Lu"
   */
  category: string;

  /**
   * The code point.
   *
   * @example 330
   */
  codePoint: number;

  /**
   * The ASCII the planned rules keep from it, often nothing.
   *
   * @example ""
   */
  folded: string;

  /**
   * The audit group it's listed under.
   *
   * @example "letter"
   */
  group: FoldGroup;
};

/** One group the audit lists. */
export type FoldGroup = keyof typeof FOLD_GROUPS;

const FOLD_GROUP_NAMES: ReadonlySet<string> = new Set(Object.keys(FOLD_GROUPS));

/** A character that renders as nothing, shown by its escape instead. */
const INVISIBLE = /^[\p{Z}\p{Cf}]$/u;

/**
 * Narrow the container's output to a report, at the boundary where it's
 * parsed.
 *
 * @returns the report, or `undefined` for anything else.
 */
export function parseFoldAuditReport(
  value: unknown
): FoldAuditReport | undefined {
  if (!isRecord(value) || !Array.isArray(value.rows)) {
    return undefined;
  }

  const { anyAsciiVersion, node, rows, unfoldable, unicode } = value;
  const parsedRows = rows.map(parseRow);

  if (
    typeof anyAsciiVersion !== "string" ||
    typeof node !== "string" ||
    typeof unfoldable !== "number" ||
    typeof unicode !== "string" ||
    !parsedRows.every((row) => row !== undefined)
  ) {
    return undefined;
  }

  return { anyAsciiVersion, node, rows: parsedRows, unfoldable, unicode };
}

/**
 * Render a report as the audit's Markdown: a summary, then one table per
 * group.
 *
 * @returns the Markdown, ending in a newline.
 */
export function renderFoldAudit(report: FoldAuditReport): string {
  const groups = Object.entries(FOLD_GROUPS).map(([group, heading]) => ({
    heading,
    rows: report.rows.filter((row) => row.group === group),
  }));

  const summary = groups.map(
    ({ heading, rows }) => `| ${heading} | ${String(rows.length)} |`
  );

  const sections = groups.map(({ heading, rows }) =>
    [
      `## ${heading}`,
      "",
      "| Code point | Character | Category | Folds to | any-ascii |",
      "| :--- | :--- | :--- | :--- | :--- |",
      ...rows.map(
        (row) =>
          `| ${codePointLabel(row.codePoint)} | ${characterCell(row.codePoint)} | ${row.category} | ${textCell(row.folded)} | ${textCell(row.anyAscii)} |`
      ),
    ].join("\n")
  );

  return `${[
    "<!-- Generated by `pnpm research:audit`; edit `research/adapters/fold-audit/rules.mts` instead. -->",
    "",
    "# `toBasicAscii` fold audit",
    "",
    "Every assigned code point the planned rules in [research/adapters/fold-audit/rules.mts](../adapters/fold-audit/rules.mts) can't fold to ASCII, in the groups a Latin-only table could cover. any-ascii's spelling is a reference, not a proposal.",
    "",
    `- **Unicode**: ${report.unicode}, from Node ${report.node}; any-ascii ${report.anyAsciiVersion}.`,
    `- **Unfoldable code points**: ${String(report.unfoldable)} in all, ${String(report.rows.length)} listed below; the rest are other scripts and symbols.`,
    "",
    "| Group | Listed |",
    "| :--- | ---: |",
    ...summary,
    "",
    ...sections.flatMap((section) => [section, ""]),
  ]
    .join("\n")
    .trimEnd()}\n`;
}

/** Show a character in a code span, or by its escape when it's invisible. */
function characterCell(codePoint: number): string {
  const char = String.fromCodePoint(codePoint);

  return INVISIBLE.test(char)
    ? `\`\\u{${codePoint.toString(16).toUpperCase()}}\``
    : textCell(char);
}

/** Label a code point as `U+00AB`. */
function codePointLabel(codePoint: number): string {
  return `U+${codePoint.toString(16).toUpperCase().padStart(4, "0")}`;
}

/** Whether a value names one of the audit's groups. */
function isFoldGroup(value: unknown): value is FoldGroup {
  return typeof value === "string" && FOLD_GROUP_NAMES.has(value);
}

/** Whether a value is a non-null, non-array object. */
function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** Narrow one row, or `undefined` when it isn't one. */
function parseRow(value: unknown): FoldAuditRow | undefined {
  if (!isRecord(value)) {
    return undefined;
  }

  const { anyAscii, category, codePoint, folded, group } = value;

  return typeof anyAscii === "string" &&
    typeof category === "string" &&
    typeof codePoint === "number" &&
    typeof folded === "string" &&
    isFoldGroup(group)
    ? { anyAscii, category, codePoint, folded, group }
    : undefined;
}

/** Show text in a table cell's code span, or `—` when it's empty. */
function textCell(text: string): string {
  if (text === "") {
    return "—";
  }

  const escaped = text.replaceAll("|", "\\|");

  return escaped.includes("`") ? `\`\` ${escaped} \`\`` : `\`${escaped}\``;
}
