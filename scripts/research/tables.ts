import type { EncodedValue } from "./codec.ts";
import type { FunctionResult, Outcome, ResultColumn } from "./results.ts";

import { renderValue } from "./codec.ts";

/** One case's outcome, and the value columns of the grouped table. */
type GroupedCellInput = {
  /**
   * The case's outcome in one column, if it has one.
   *
   * @example `{ kind: "value", value: true }`
   */
  outcome: Outcome | undefined;

  /**
   * The rendered values that get a column of their own.
   *
   * @example `["true", "false", "undefined"]`
   */
  values: readonly string[];
};

/** The most distinct return values a function can have for the grouped table. */
const GROUPED_MAX_VALUES = 4;

/** The highest tier the summary table shows, the one decision records quote. */
const SUMMARY_MAX_TIER = 2;

/** Escape a Markdown table cell's pipes. @returns the escaped text. */
export function escapeTableCell(text: string): string {
  return text.replaceAll("|", String.raw`\|`);
}

/**
 * Render one function's results as the Markdown file beside its JSON.
 *
 * - **Summary**: tiers 0–2, one row per case, for a decision record.
 *
 * - **By outcome**: one row per column, listing the cases that returned each
 *   of the planned column's values, then any other value, then a throw; only
 *   for functions with a handful of distinct values, such as a boolean
 *   parser.
 *
 * - **Every tool**: the full master table, then each column's version,
 *   locale, and image.
 *
 * @returns the Markdown text, ending in a newline.
 */
export function renderResultMarkdown(result: FunctionResult): string {
  const summaryColumns = result.columns.filter(
    ({ tier }) => tier <= SUMMARY_MAX_TIER
  );

  const sections = [
    "<!-- Generated by `pnpm research`; edit `research/cases/` or an adapter instead. -->",
    `# \`${result.function}\``,
    `## Tiers 0–${SUMMARY_MAX_TIER}`,
    renderCaseTable({ cases: result.cases, columns: summaryColumns }),
    ...renderGroupedSection(result),
    "## Every tool",
    renderCaseTable({ cases: result.cases, columns: result.columns }),
    "## Versions",
    renderVersionTable(result.columns),
  ];

  return `${sections.join("\n\n")}\n`;
}

/** Wrap text in a Markdown code span, safe inside a table cell. */
function codeSpan(text: string): string {
  const escaped = escapeTableCell(text);

  return escaped.includes("`") ? `\`\` ${escaped} \`\`` : `\`${escaped}\``;
}

/**
 * Pick the cell a case belongs in: one of `values`, then "Other", then
 * "Throws"; `n/a` cases are left out.
 *
 * @returns the cell's index, or `undefined` to leave the case out.
 */
function groupedCellIndex({
  outcome,
  values,
}: GroupedCellInput): number | undefined {
  if (outcome === undefined || outcome.kind === "n/a") {
    return undefined;
  }

  if (outcome.kind === "error") {
    return values.length + 1;
  }

  const index = values.indexOf(renderValue(outcome.value));

  return index === -1 ? values.length : index;
}

/**
 * The values the grouped table gets a column for: the planned column's
 * values, or every column's when there is no plan, and only when there are
 * few enough to read as columns.
 *
 * @returns the rendered values, or an empty list to skip the table.
 */
function groupedValues(result: FunctionResult): string[] {
  const planned = result.columns.filter(({ tier }) => tier === 0);

  const values = [
    ...new Set(
      (planned.length > 0 ? planned : result.columns).flatMap(({ outcomes }) =>
        outcomes.flatMap((outcome) =>
          outcome.kind === "value" ? [renderValue(outcome.value)] : []
        )
      )
    ),
  ];

  return values.length > GROUPED_MAX_VALUES ? [] : values;
}

/** Render a case's arguments as one code span. */
function renderArgs(args: readonly EncodedValue[]): string {
  return codeSpan(args.map((arg) => renderValue(arg)).join(", "));
}

/** Render one row per case and one column per call. */
function renderCaseTable({
  cases,
  columns,
}: Pick<FunctionResult, "cases" | "columns">): string {
  const header = ["Case", ...columns.map((column) => renderHeader(column))];

  const rows = cases.map((args, index) => [
    renderArgs(args),
    ...columns.map((column) => renderOutcome(column.outcomes[index])),
  ]);

  return renderTable([header, ...rows]);
}

/** Render the by-outcome section, or nothing when it would be unreadable. */
function renderGroupedSection(result: FunctionResult): string[] {
  const values = groupedValues(result);

  if (values.length === 0) {
    return [];
  }

  const header = [
    "Tool",
    ...values.map((value) => codeSpan(value)),
    "Other",
    "Throws",
  ];

  const rows = result.columns.map((column) => {
    const cells = result.cases.reduce<string[][]>(
      (casesByCell, args, index) => {
        const outcome = column.outcomes[index];
        const cellIndex = groupedCellIndex({ outcome, values });

        if (cellIndex !== undefined) {
          casesByCell[cellIndex]?.push(
            cellIndex === values.length && outcome?.kind === "value"
              ? `${renderArgs(args)} → ${codeSpan(renderValue(outcome.value))}`
              : renderArgs(args)
          );
        }

        return casesByCell;
      },
      Array.from({ length: values.length + 2 }, () => [])
    );

    return [renderHeader(column), ...cells.map((cell) => cell.join(" "))];
  });

  return ["## By outcome", renderTable([header, ...rows])];
}

/** Render a column's header: its tool, marked if docs-only, then its call. */
function renderHeader(column: ResultColumn): string {
  const marker = column.source === undefined ? "" : " (docs only)";

  return `${column.name}${marker}<br>${codeSpan(column.call)}`;
}

/** Render one outcome as a table cell. */
function renderOutcome(outcome: Outcome | undefined): string {
  if (outcome === undefined || outcome.kind === "n/a") {
    return "—";
  }

  return outcome.kind === "error"
    ? `💥 ${codeSpan(outcome.error)}`
    : codeSpan(renderValue(outcome.value));
}

/** Render rows as a Markdown table, the first row as its header. */
function renderTable(rows: readonly (readonly string[])[]): string {
  const [header = [], ...body] = rows;

  return [header, header.map(() => ":---"), ...body]
    .map((cells) => `| ${cells.join(" | ")} |`)
    .join("\n");
}

/**
 * Render every column's version, locale, and origin: the image it ran in, or
 * the cached source a docs-only column was transcribed from.
 */
function renderVersionTable(columns: readonly ResultColumn[]): string {
  return renderTable([
    ["Tool", "Tier", "Version", "Locale", "Image or source"],
    ...columns.map((column) => [
      renderHeader(column),
      String(column.tier),
      codeSpan(column.version),
      codeSpan(column.locale),
      codeSpan(column.source ?? column.image),
    ]),
  ]);
}
